#!/usr/bin/env node
// Writes sw.js with the list of files to cache for offline use, versioned by content hash.
// Run after changing any app file:  node tools/build-sw.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

const files = ['./', 'index.html', 'editor.html', 'manifest.webmanifest'];
const dirs = ['css', 'js', 'fonts', 'assets/piano', 'assets/icons', 'songs/demo'];
function walk(d) {
  for (const f of readdirSync(d).sort()) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (!/\.(md|txt|map)$/i.test(f) && !f.startsWith('.')) files.push(p);
  }
}
dirs.forEach(walk);
files.push('assets/island-bg.jpg', 'songs/index.json', 'songs/twinkle.txt', 'songs/mary.txt', 'songs/ode.txt', 'songs/frere-jacques.txt');
const hash = createHash('sha1');
for (const f of files) if (f !== './' && existsSync(f)) hash.update(f).update(readFileSync(f));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by tools/build-sw.mjs — offline cache for the practice player.
const CACHE = 'note-player-${version}';
const PRECACHE = ${JSON.stringify(files, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('note-player-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // App files: cache first (works offline), falling back to the network.
  // Anything else (e.g. songs/local.json): network first, cached copy when offline.
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req)
        .then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => (req.mode === 'navigate' ? caches.match('index.html') : Response.error()));
    }),
  );
});
`;
writeFileSync('sw.js', sw);
console.log(`sw.js: ${files.length} files, cache note-player-${version}`);
